import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { zipSync } from "fflate";

const PKG_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FIXTURES = join(PKG_ROOT, "fixtures");

// Fixed mtime for zip entries so archives are byte-stable across runs.
const FIXED_MTIME = new Date("2026-08-12T01:05:00Z");

function writeExchange(connectorId, filename, exchange) {
  const dir = join(FIXTURES, connectorId, "exchanges");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, filename), JSON.stringify(exchange, null, 2) + "\n");
}

function writeReadme(connectorId, title, specNote) {
  const dir = join(FIXTURES, connectorId);
  mkdirSync(dir, { recursive: true });
  const body = `# Fixtures — ${title}

fixture_provenance: synthetic-from-spec

Every file in this directory is SYNTHETIC test data, generated by
\`scripts/make-fixtures.mjs\` from the source's published format
specification. No fixture here is real recorded data, and nothing in this
package claims live verification of the source (egress-blocked build; see
docs/LEGAL-LICENSING.md and the workspace honesty rules).

Format spec bound against: ${specNote}

Regenerate with: \`npm run make-fixtures -w @pact-tailor/connectors\`
(deterministic — fixed timestamps around 2026-08-12T01:00Z, no randomness).
`;
  writeFileSync(join(dir, "README.md"), body);
}

function zipOf(entryName, text) {
  const zipped = zipSync({ [entryName]: [new TextEncoder().encode(text), { mtime: FIXED_MTIME }] }, { level: 6 });
  return Buffer.from(zipped).toString("base64");
}

function iisListing(dirPath, names) {
  const links = names
    .map((n) => `<A HREF="${dirPath}${n}">${n}</A><br>`)
    .join("");
  return (
    `<html><head><title>nemweb.com.au - ${dirPath}</title></head>` +
    `<body><H1>nemweb.com.au - ${dirPath}</H1><hr><pre>` +
    `<A HREF="${dirPath.replace(/[^/]+\/$/, "")}">[To Parent Directory]</A><br>${links}` +
    `</pre><hr></body></html>`
  );
}

